def specialprint(text, code=None, code1=None, RESET = '\033[0m'):

    try:
        str(text)
    except Exception as e:
        print("[!] {}".format(e))

    if code is None and code1 is None:
        print(text)
    elif code is None:
        print(f"{code1}{text}{RESET}")
    elif code1 is None:
        print(f"{code}{text}{RESET}")
    else:
        print(f"{code}{code1}{text}{RESET}")

